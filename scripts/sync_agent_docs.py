#!/usr/bin/env python3
"""Export the repository agent guide from the same source as /help and /help.md."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def sync(*, check=False):
    source = json.loads((ROOT / 'backend/routers/help_content.json').read_text())
    content = '<!-- Generated by scripts/sync_agent_docs.py. Edit backend/routers/help_content.json. -->\n\n'
    content += f"# {source['title']}\n\n{source['content']}\n"
    target = ROOT / 'docs/agents.md'
    if check:
        if not target.exists() or target.read_text() != content:
            raise RuntimeError('Agent guide is stale. Run python3 scripts/sync_agent_docs.py')
    else:
        target.write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        sync(check=args.check)
    except RuntimeError as error:
        raise SystemExit(str(error)) from None

if __name__ == '__main__':
    main()
